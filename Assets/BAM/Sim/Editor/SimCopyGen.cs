using System;
using System.Collections.Generic;
using System.Linq;
using System.Reflection;
using System.Text;

// Writes Assets/BAM/Sim/SimCopy.g.cs: for every sim class SimMirror.Types() lists, a typed copy of every field (no reflection at
// run time, so the guest's prediction can copy the whole match every frame on a phone). Run by the editor when the sim classes
// changed (SimCopyAuto.cs) and headless by bam-work/online/tools/simcopy/run.sh. Engine-free on purpose.
namespace BAM.Sim.EditorTools
{
    public static class SimCopyGen
    {
        const BindingFlags All = SimMirror.All;

        public static string Generate()
        {
            var types = SimMirror.Types();
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated> by Assets/BAM/Sim/Editor/SimCopyGen.cs. Do not edit: make it again (BAM > Online > Regenerate SimCopy,");
            sb.AppendLine("// or headless bash bam-work/online/tools/simcopy/run.sh) when a sim class changes. If it no longer compiles after a field was");
            sb.AppendLine("// renamed or removed, delete this file: the game then plays without the guest's prediction until it is made again.");
            sb.AppendLine("#pragma warning disable");
            sb.AppendLine("namespace BAM.Sim");
            sb.AppendLine("{");
            sb.AppendLine("    public sealed partial class SimMirror");
            sb.AppendLine("    {");
            sb.AppendLine("        static partial void Init()");
            sb.AppendLine("        {");
            sb.AppendLine("            Generated = true; GeneratedHash = \"" + SimMirror.Hash() + "\";");
            sb.AppendLine("            TwinOf = Match.__TwinAny; CopyInto = Match.__CopyAny;");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            // the dispatch lives in Match, so Match's private nested classes are reachable
            sb.AppendLine("    public sealed partial class Match");
            sb.AppendLine("    {");
            sb.AppendLine("        internal static object __TwinAny(object o, SimMirror m)");
            sb.AppendLine("        {");
            sb.AppendLine("            switch (o)");
            sb.AppendLine("            {");
            foreach (var t in types) sb.AppendLine("                case " + N(t) + " x: return " + N(t) + ".__Twin(x, m);");
            sb.AppendLine("            }");
            sb.AppendLine("            throw new System.InvalidOperationException(\"SimMirror: no twin for \" + o.GetType());");
            sb.AppendLine("        }");
            sb.AppendLine("        internal static void __CopyAny(object d, object s, SimMirror m)");
            sb.AppendLine("        {");
            sb.AppendLine("            switch (s)");
            sb.AppendLine("            {");
            foreach (var t in types) sb.AppendLine("                case " + N(t) + " x: ((" + N(t) + ")d).__Copy(x, m); return;");
            sb.AppendLine("            }");
            sb.AppendLine("            throw new System.InvalidOperationException(\"SimMirror: no copy for \" + s.GetType());");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            foreach (var t in types)
            {
                if (t.IsNested && t.DeclaringType != typeof(Match)) throw new Exception(t + ": a nested sim class must be nested in Match");
                var chain = new List<Type>(); for (var x = t; x != null; x = x.DeclaringType) chain.Insert(0, x);
                int ind = 1;
                foreach (var c in chain) { sb.Append(' ', ind * 4).AppendLine("partial class " + c.Name); sb.Append(' ', ind * 4).AppendLine("{"); ind++; }
                string p = new string(' ', ind * 4), n = N(t);
                var fs = t.GetFields(All).OrderBy(f => f.Name, StringComparer.Ordinal).ToArray();
                // the twin: a shallow copy, then its own containers and objects for readonly fields
                sb.AppendLine(p + "internal static object __Twin(" + n + " __s, SimMirror __m)");
                sb.AppendLine(p + "{");
                sb.AppendLine(p + "    var __t = (" + n + ")__s.MemberwiseClone();");
                foreach (var f in fs) if (f.IsInitOnly) { var v = NewFor(f.FieldType, "__s." + f.Name); if (v != null) sb.AppendLine(p + "    SimMirror.SetRo(__t, \"" + f.Name + "\", " + v + ");"); }
                sb.AppendLine(p + "    return __t;");
                sb.AppendLine(p + "}");
                sb.AppendLine(p + "internal void __Copy(" + n + " __s, SimMirror __m)");
                sb.AppendLine(p + "{");
                foreach (var f in fs) foreach (var line in CopyField(t, f)) sb.AppendLine(p + "    " + line);
                sb.AppendLine(p + "}");
                for (int i = chain.Count; i > 0; i--) { ind--; sb.Append(' ', ind * 4).AppendLine("}"); }
            }
            sb.AppendLine("}");
            return sb.ToString();
        }

        // a new value for a readonly field of a twin, or null when the shallow copy is right (values, shared classes)
        static string NewFor(Type ft, string src)
        {
            if (ft.IsValueType || SimMirror.Shared(ft)) return null;
            if (SimMirror.Mapped(ft)) return null; // pointed at its twin by __Copy, after the twin is known (BotBrain.H -> Unit.Bot -> BotBrain)
            if (ft.IsArray) return ft.GetElementType().IsArray ? "SimMirror.NewJag(" + src + ")" : "SimMirror.NewArr(" + src + ")";
            if (Gen(ft, typeof(List<>))) return "SimMirror.NewList(" + src + ")";
            if (Gen(ft, typeof(Dictionary<,>))) return "SimMirror.NewDict(" + src + ")";
            if (Gen(ft, typeof(HashSet<>))) return "SimMirror.NewSet(" + src + ")";
            if (Gen(ft, typeof(Queue<>))) return "SimMirror.NewQue(" + src + ")";
            throw new Exception("SimCopyGen: cannot copy a field of type " + ft);
        }

        static IEnumerable<string> CopyField(Type owner, FieldInfo f)
        {
            Type ft = f.FieldType; string a = f.Name, s = "__s." + f.Name; bool ro = f.IsInitOnly;
            if (ft.IsValueType)
            {
                if (ro) yield break; // set once when made, the same in src and dst
                if (!HasRefs(ft)) { yield return a + " = " + s + ";"; yield break; }
                yield return "{ var __e = " + s + "; " + Fix(ft, "__e") + " " + a + " = __e; }";
                yield break;
            }
            if (SimMirror.Shared(ft)) { if (!ro) yield return a + " = " + s + ";"; yield break; }
            if (SimMirror.Mapped(ft))
            {
                if (!ro) yield return a + " = __m.Map(" + s + ");";
                else yield return "if (!ReferenceEquals(" + a + ", __m.Map(" + s + "))) SimMirror.SetRo(this, \"" + a + "\", __m.Map(" + s + "));";
                yield break;
            }
            if (ft.IsArray)
            {
                var et = ft.GetElementType();
                if (et.IsArray)
                {
                    if (!ro || HasRefs(et.GetElementType()) || !et.GetElementType().IsValueType) throw new Exception("SimCopyGen: " + owner + "." + a + ": only readonly jagged arrays of values");
                    yield return "SimMirror.Jag(" + a + ", " + s + ");"; yield break;
                }
                string make = ro ? "" : "if (" + s + " == null) " + a + " = null; else if (" + a + " == null || " + a + ".Length != " + s + ".Length || ReferenceEquals(" + a + ", " + s + ")) " + a + " = new " + N(et) + "[" + s + ".Length]; ";
                if ((et.IsValueType && !HasRefs(et)) || SimMirror.Shared(et)) { yield return make + "SimMirror.Arr(" + a + ", " + s + ");"; yield break; }
                if (SimMirror.Mapped(et)) { yield return make + "__m.ArrMap(" + a + ", " + s + ");"; yield break; }
                if (et.IsValueType) { yield return make + "if (" + s + " != null) for (int __i = 0; __i < " + s + ".Length; __i++) { var __e = " + s + "[__i]; " + Fix(et, "__e") + " " + a + "[__i] = __e; }"; yield break; }
                throw new Exception("SimCopyGen: " + owner + "." + a + ": cannot copy an array of " + et);
            }
            if (Gen(ft, typeof(List<>)))
            {
                var et = ft.GetGenericArguments()[0];
                string make = ro ? "" : "if (" + s + " == null) " + a + " = null; else if (" + a + " == null || ReferenceEquals(" + a + ", " + s + ")) " + a + " = new " + N(ft) + "(" + s + ".Capacity); ";
                if ((et.IsValueType && !HasRefs(et)) || SimMirror.Shared(et)) { yield return make + "SimMirror.List(" + a + ", " + s + ");"; yield break; }
                if (SimMirror.Mapped(et)) { yield return make + "__m.ListMap(" + a + ", " + s + ");"; yield break; }
                if (et.IsValueType) { yield return make + "if (" + s + " != null) { " + a + ".Clear(); for (int __i = 0; __i < " + s + ".Count; __i++) { var __e = " + s + "[__i]; " + Fix(et, "__e") + " " + a + ".Add(__e); } }"; yield break; }
                throw new Exception("SimCopyGen: " + owner + "." + a + ": cannot copy a list of " + et);
            }
            foreach (var (g, h) in new[] { (typeof(Dictionary<,>), "Dict"), (typeof(HashSet<>), "Set"), (typeof(Queue<>), "Que") })
            {
                if (!Gen(ft, g)) continue;
                foreach (var x in ft.GetGenericArguments()) if (!(x.IsValueType && !HasRefs(x)) && !SimMirror.Shared(x)) throw new Exception("SimCopyGen: " + owner + "." + a + ": only values in a " + h);
                string make = ro ? "" : "if (" + s + " == null) " + a + " = null; else if (" + a + " == null || ReferenceEquals(" + a + ", " + s + ")) " + a + " = new " + N(ft) + "(); ";
                yield return make + "SimMirror." + h + "(" + a + ", " + s + ");";
                yield break;
            }
            throw new Exception("SimCopyGen: " + owner + "." + a + ": cannot copy a field of type " + ft);
        }

        // the mapped references inside a struct value v (fields reached by name, so they must be public or internal)
        static string Fix(Type st, string v)
        {
            var sb = new StringBuilder();
            foreach (var f in st.GetFields(All).OrderBy(f => f.Name, StringComparer.Ordinal))
            {
                var ft = f.FieldType;
                if (ft.IsValueType ? !HasRefs(ft) : !SimMirror.Mapped(ft)) continue;
                if (!(f.IsPublic || f.IsAssembly)) throw new Exception("SimCopyGen: " + st + "." + f.Name + " holds a sim object: make it public or internal");
                if (f.IsInitOnly) throw new Exception("SimCopyGen: " + st + "." + f.Name + " is readonly and holds a sim object");
                if (ft.IsValueType) sb.Append("{ var __e2 = " + v + "." + f.Name + "; " + Fix(ft, "__e2") + " " + v + "." + f.Name + " = __e2; } ");
                else sb.Append(v + "." + f.Name + " = __m.Map(" + v + "." + f.Name + "); ");
            }
            return sb.ToString().TrimEnd();
        }

        static readonly Dictionary<Type, bool> refs = new Dictionary<Type, bool>();
        // a struct that holds (maybe inside another struct) a reference to a sim object
        static bool HasRefs(Type t)
        {
            if (!t.IsValueType || t.IsPrimitive || t.IsEnum) return false;
            if (refs.TryGetValue(t, out var r)) return r;
            refs[t] = false;
            foreach (var f in t.GetFields(All))
            {
                var ft = f.FieldType;
                if (ft.IsValueType ? HasRefs(ft) : !SimMirror.Shared(ft)) { r = true; break; }
            }
            return refs[t] = r;
        }

        static bool Gen(Type t, Type g) => t.IsGenericType && t.GetGenericTypeDefinition() == g;

        // the C# name of a type
        static string N(Type t)
        {
            if (t.IsArray) return N(t.GetElementType()) + "[" + new string(',', t.GetArrayRank() - 1) + "]";
            if (t.IsGenericType)
            {
                string b = t.GetGenericTypeDefinition().FullName; b = b.Substring(0, b.IndexOf('`'));
                return "global::" + b.Replace('+', '.') + "<" + string.Join(", ", t.GetGenericArguments().Select(N)) + ">";
            }
            return "global::" + t.FullName.Replace('+', '.');
        }
    }
}
